"""Build the PC simulator, run every LED program, and save an animated GIF of each
into previews/ at the repo root.

    pip install pillow
    python tools/preview/make_gifs.py            # all programs
    python tools/preview/make_gifs.py 3 9        # just programs 3 and 9

Needs Windows with Visual Studio (C++ workload) and the Adafruit GFX library
installed for the Arduino IDE. See build.bat.
"""
import re
import subprocess
import sys
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
SKETCH = REPO / "SliceCartWithTimeManager" / "SliceCartWithTimeManager.ino"
BUILD = HERE / "build"
OUT = REPO / "previews"

FPS = 20

# program number: (file name, title, seconds to record). Logo programs record
# exactly one loop of their animation so the GIF loops seamlessly.
PROGRAMS = {
    1: ("team-logo", "Team logo", 3.6),
    2: ("logo-zoom", "Logo zoom", 6.4),
    3: ("logo-spin", "Logo spin", 5.2),
    4: ("logo-roll", "Logo roll", 6.5),
    5: ("logo-squeeze", "Logo squeeze", 4.3),
    6: ("logo-sunrise", "Logo sunrise", 6.6),
    7: ("prism-logo", "Prism logo", 4),
    8: ("rainbow-wave", "Rainbow wave", 4.1),
    9: ("plasma", "Plasma", 6),
    10: ("confetti", "Confetti", 5),
    11: ("rainbow-beat", "Rainbow beat", 6),
    12: ("rainbow-chant", "Rainbow + color-changing chant", 13.85),
    13: ("rainbow-letters-chant", "Rainbow + rainbow-letter chant", 13.85),
    14: ("sound-meter", "Sound meter + SLICE / 8738", 6),
    15: ("blink-inverted", "Orange blink + inverted SLICE / 8738", 6),
    16: ("letter-by-letter", "Letter by letter", 4.3),
    17: ("letters-blink-chant", "Letters, blink + orange chant", 13.85),
    18: ("vertical-rainbow", "Wrap-around rainbow", 6),
    19: ("headlights", "Headlights", 8.2),
}

NUM_LEDS = 300
MW, MH = 64, 16

# ---------------------------------------------------------------------------
# Build
# ---------------------------------------------------------------------------

def write_prototypes():
    """Do what the Arduino IDE does: declare every top-level function up front."""
    protos = []
    src = SKETCH.read_text()
    types = "void|int|bool|boolean|uint8_t|uint16_t|float|String|unsigned long|SlicePose"
    for m in re.finditer(rf"^(?:{types})\s+\w+\s*\([^)]*\)\s*\{{", src, re.M):
        sig = m.group(0).rstrip("{").strip()
        if not sig.startswith(("void setup", "void loop")):
            protos.append(sig + ";")
    # Declare the sketch's structs first so prototypes can mention them
    structs = [f"struct {name};" for name in re.findall(r"^struct (\w+)", src, re.M)]
    BUILD.mkdir(exist_ok=True)
    (BUILD / "prototypes.h").write_text("// Generated by make_gifs.py\n" + "\n".join(structs + protos) + "\n")


def build():
    write_prototypes()
    r = subprocess.run(["cmd", "/c", str(HERE / "build.bat")], capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout, r.stderr)
        sys.exit("build failed")


# ---------------------------------------------------------------------------
# Rendering
# ---------------------------------------------------------------------------

# Rows of the side strip that make up each letter (row 0 = bottom of the E)
LETTER_ROWS = {"S": (34, 42), "L": (26, 33), "I": (17, 25), "C": (8, 16), "E": (0, 7)}
ROWS = 43
ROW_PX = 6          # screen pixels per LED row on the side panels
PANEL_W = 60        # width of a side panel letter
LED_PX = 7          # screen pixels per matrix LED
PAD, GAP, TITLE_H, FOOT_H = 20, 30, 40, 26
PANEL_H = ROWS * ROW_PX
MAT_W, MAT_H = MW * LED_PX, MH * LED_PX
W = PAD * 2 + PANEL_W * 2 + GAP * 2 + MAT_W
H = TITLE_H + PANEL_H + FOOT_H
BG = (12, 12, 14)
UNLIT = (38, 38, 42)


def font(size, bold=False):
    for name in (("arialbd.ttf", "DejaVuSans-Bold.ttf") if bold else ("arial.ttf", "DejaVuSans.ttf")):
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            pass
    return ImageFont.load_default(size)


def column_leds(col):
    """(strip index, row) pairs for side column 1-6 (see setColumn/setRow in the sketch)."""
    if col == 1: return [(i, i) for i in range(0, 42)]
    if col == 2: return [(i, 84 - i) for i in range(42, 85)]
    if col == 3: return [(i, i - 85) for i in range(85, 128)]
    if col == 4: return [(i, i - 171) for i in range(171, 214)]
    if col == 5: return [(i, 256 - i) for i in range(214, 257)]
    if col == 6: return [(i, i - 257) for i in range(257, 299)]


def letter_mask():
    """White S-L-I-C-E stacked top to bottom, each stretched to fill its rows."""
    mask = Image.new("L", (PANEL_W, PANEL_H), 0)
    f = font(120, bold=True)
    for letter, (lo, hi) in LETTER_ROWS.items():
        g = Image.new("L", (140, 140), 0)
        ImageDraw.Draw(g).text((10, -10), letter, font=f, fill=255)
        g = g.crop(g.getbbox())
        top = (ROWS - 1 - hi) * ROW_PX + 2
        h = (hi - lo + 1) * ROW_PX - 4
        w = min(PANEL_W - 6, round(g.width * h / g.height * 1.3))  # keep shape, a bit wide
        mask.paste(g.resize((w, h), Image.LANCZOS), ((PANEL_W - w) // 2, top))
    return mask


# The side strip gets raw RGB values, which look much brighter on real LEDs than
# on a screen (e.g. the sketch's 255,50,0 reads as orange, not red). Brighten
# them so the preview matches what you see. The matrix library already
# gamma-corrects, so its colors are used as-is.
STRIP_GAMMA = [round(255 * (v / 255) ** (1 / 2.2)) for v in range(256)]


def dot_mask():
    """Round LED dots for the matrix."""
    m = Image.new("RGB", (MAT_W, MAT_H), (0, 0, 0))
    d = ImageDraw.Draw(m)
    for y in range(MH):
        for x in range(MW):
            d.ellipse([x * LED_PX + 1, y * LED_PX + 1, (x + 1) * LED_PX - 2, (y + 1) * LED_PX - 2],
                      fill=(255, 255, 255))
    return m


def make_background(title, number):
    bg = Image.new("RGB", (W, H), BG)
    d = ImageDraw.Draw(bg)
    d.text((PAD, 10), f"{number}  {title}", font=font(18, bold=True), fill=(235, 235, 235))
    small = font(12)
    y = TITLE_H + PANEL_H + 6
    d.text((PAD, y), "right side", font=small, fill=(130, 130, 130))
    d.text((W - PAD - PANEL_W, y), "left side", font=small, fill=(130, 130, 130))
    d.text((PAD + PANEL_W + GAP, TITLE_H + (PANEL_H + MAT_H) // 2 + 6),
           "matrix display (64 x 16)", font=small, fill=(130, 130, 130))
    return bg


def render_panel(strip, cols, mask):
    """Light the letter shapes with the colors of the given strip columns."""
    grid = Image.new("RGB", (3, ROWS), (0, 0, 0))
    for x, col in enumerate(cols):
        for idx, row in column_leds(col):
            grid.putpixel((x, ROWS - 1 - row), strip[idx])
    grid = grid.point(STRIP_GAMMA * 3).resize((PANEL_W, PANEL_H), Image.NEAREST)
    lit = ImageChops.lighter(grid, Image.new("RGB", grid.size, UNLIT))
    panel = Image.new("RGB", grid.size, BG)
    panel.paste(lit, (0, 0), mask)
    return panel


def render(bin_path, gif_path, title, number):
    data = bin_path.read_bytes()
    frame_bytes = (NUM_LEDS + MW * MH) * 3
    bg = make_background(title, number)
    mask, dots = letter_mask(), dot_mask()
    unlit = Image.new("RGB", (MAT_W, MAT_H), UNLIT)
    mat_y = TITLE_H + (PANEL_H - MAT_H) // 2

    frames = []
    for off in range(0, len(data) - frame_bytes + 1, frame_bytes):
        raw = data[off:off + frame_bytes]
        strip = [tuple(raw[i * 3:i * 3 + 3]) for i in range(NUM_LEDS)]
        mat = Image.frombytes("RGB", (MW, MH), raw[NUM_LEDS * 3:])
        mat = ImageChops.multiply(ImageChops.lighter(mat.resize((MAT_W, MAT_H), Image.NEAREST), unlit), dots)

        f = bg.copy()
        f.paste(render_panel(strip, (1, 2, 3), mask), (PAD, TITLE_H))
        f.paste(mat, (PAD + PANEL_W + GAP, mat_y))
        f.paste(render_panel(strip, (4, 5, 6), mask), (W - PAD - PANEL_W, TITLE_H))
        frames.append(f)

    frames[0].save(gif_path, save_all=True, append_images=frames[1:],
                   duration=1000 // FPS, loop=0, optimize=True)
    return len(frames)


def main():
    wanted = [int(a) for a in sys.argv[1:]] or list(PROGRAMS)
    build()
    OUT.mkdir(exist_ok=True)
    for n in wanted:
        name, title, secs = PROGRAMS[n]
        bin_path = BUILD / f"program{n}.bin"
        subprocess.run([str(BUILD / "sim.exe"), str(n), str(secs), str(FPS), str(bin_path)], check=True,
                       capture_output=True)
        gif = OUT / f"{n:02d}-{name}.gif"
        count = render(bin_path, gif, title, n)
        print(f"{gif.relative_to(REPO)}: {count} frames, {gif.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
